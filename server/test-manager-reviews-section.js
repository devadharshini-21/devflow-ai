const path = require("path");
require("dotenv").config({ path: path.resolve(__dirname, ".env") });
const mongoose = require("mongoose");
const jwt = require("jsonwebtoken");
const http = require("http");
const app = require("./app");

const User = require("./models/User");
const Project = require("./models/Project");
const ProjectAnalysis = require("./models/ProjectAnalysis");
const DeveloperCodeFinding = require("./models/DeveloperCodeFinding");

async function runManagerReviewsVerification() {
  console.log("==================================================");
  console.log("DEVFLOW AI - MANAGER AI REVIEWS SECTION VERIFICATION");
  console.log("==================================================");

  await mongoose.connect(process.env.MONGO_URI);
  console.log("✓ Connected to MongoDB Atlas");

  const project = await Project.findOne({ name: "E-Commerce Platform" });
  if (!project) {
    throw new Error("E-Commerce Platform project not found in MongoDB");
  }
  console.log(`✓ Project: "${project.name}" (ID: ${project._id})`);

  // Start test server
  const server = http.createServer(app);
  await new Promise((resolve) => server.listen(0, resolve));
  const port = server.address().port;
  const baseUrl = `http://localhost:${port}`;
  console.log(`✓ Test Server running on ${baseUrl}`);

  const generateToken = (user) => {
    return jwt.sign(
      { id: user._id, role: user.role, email: user.email },
      process.env.JWT_SECRET,
      { expiresIn: "1h" }
    );
  };

  // 1. Get Manager and Developers
  const manager = await User.findOne({ email: "devadharshini@gmail.com" });
  const frontendDev = await User.findOne({ email: "abirami@gmail.com" });
  const backendDev = await User.findOne({ email: "varma@gmail.com" });
  const uiuxDev = await User.findOne({ email: "gowri@gmail.com" });
  const qaTester = await User.findOne({ email: "algox@gmail.com" });

  console.log(`✓ Team loaded:`);
  console.log(`  Manager: ${manager.name} (${manager.role})`);
  console.log(`  Frontend: ${frontendDev.name} (${frontendDev.role})`);
  console.log(`  Backend: ${backendDev.name} (${backendDev.role})`);
  console.log(`  UI/UX: ${uiuxDev.name} (${uiuxDev.role})`);
  console.log(`  QA: ${qaTester.name} (${qaTester.role})`);

  const managerToken = generateToken(manager);
  const frontendToken = generateToken(frontendDev);
  const backendToken = generateToken(backendDev);
  const uiuxToken = generateToken(uiuxDev);
  const qaToken = generateToken(qaTester);

  // --- TEST 1: MANAGER RUNS OVERALL PROJECT ANALYSIS ---
  console.log("\n--- TEST 1: Manager Overall Project Analysis Execution ---");
  const analyzeRes = await fetch(`${baseUrl}/api/code/project/${project._id}/ai-insights`, {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      Authorization: `Bearer ${managerToken}`,
    },
  });

  console.log("Overall Analysis status:", analyzeRes.status);
  const analyzeData = await analyzeRes.json();
  if (!analyzeData.success) {
    throw new Error(`Overall analysis failed: ${JSON.stringify(analyzeData)}`);
  }
  console.log("Overall Quality Score:", analyzeData.analysis?.overallQualityScore);
  console.log("Health Status:", analyzeData.analysis?.healthStatus);
  console.log("Generated By:", analyzeData.analysis?.generatedBy?.name);
  console.log("✓ TEST 1 PASSED: Manager analysis completed and persisted with run metadata.");

  // --- TEST 2: FRONTEND DEVELOPER REVIEWS ---
  console.log("\n--- TEST 2: Frontend Developer Manager AI Reviews Retrieval ---");
  const frontendRes = await fetch(`${baseUrl}/api/code/my-manager-reviews`, {
    headers: { Authorization: `Bearer ${frontendToken}` },
  });
  console.log("Frontend Dev status:", frontendRes.status);
  const frontendData = await frontendRes.json();
  if (!frontendData.success || !frontendData.reviews?.length) {
    throw new Error(`Frontend reviews failed: ${JSON.stringify(frontendData)}`);
  }

  const feReview = frontendData.reviews[0];
  console.log(`  Review ID: ${feReview._id}`);
  console.log(`  Project: ${feReview.project?.name}`);
  console.log(`  Analyzed By: ${feReview.analyzedBy?.name} (${feReview.analyzedBy?.role})`);
  console.log(`  Analyzed At: ${feReview.analyzedAt}`);
  console.log(`  Overall Score: ${feReview.overallQualityScore}`);
  console.log(`  Frontend Developer Issues Count: ${feReview.developerIssuesCount}`);
  
  // Verify only frontend files are in findings
  for (const finding of feReview.findings) {
    console.log(`    • [${finding.severity}] ${finding.title} (${finding.fileName})`);
    if (finding.fileName.includes("productController.js") || finding.fileName.includes("ecommerce.test.js")) {
      throw new Error(`PRIVACY VIOLATION: Frontend Dev received non-frontend finding: ${finding.fileName}`);
    }
  }
  console.log("✓ TEST 2 PASSED: Frontend Developer received only their own findings.");

  // --- TEST 3: BACKEND DEVELOPER REVIEWS ---
  console.log("\n--- TEST 3: Backend Developer Manager AI Reviews Retrieval ---");
  const backendRes = await fetch(`${baseUrl}/api/code/my-manager-reviews`, {
    headers: { Authorization: `Bearer ${backendToken}` },
  });
  console.log("Backend Dev status:", backendRes.status);
  const backendData = await backendRes.json();
  const beReview = backendData.reviews[0];
  console.log(`  Project: ${beReview.project?.name}`);
  console.log(`  Analyzed By: ${beReview.analyzedBy?.name}`);
  console.log(`  Backend Developer Issues Count: ${beReview.developerIssuesCount}`);
  for (const finding of beReview.findings) {
    console.log(`    • [${finding.severity}] ${finding.title} (${finding.fileName})`);
    if (finding.fileName.includes("Login.jsx") || finding.fileName.includes("ecommerce.test.js")) {
      throw new Error(`PRIVACY VIOLATION: Backend Dev received non-backend finding: ${finding.fileName}`);
    }
  }
  console.log("✓ TEST 3 PASSED: Backend Developer received only their own findings.");

  // --- TEST 4: QA TESTER REVIEWS ---
  console.log("\n--- TEST 4: QA Tester Manager AI Reviews Retrieval ---");
  const qaRes = await fetch(`${baseUrl}/api/code/my-manager-reviews`, {
    headers: { Authorization: `Bearer ${qaToken}` },
  });
  console.log("QA Tester status:", qaRes.status);
  const qaData = await qaRes.json();
  const qaReview = qaData.reviews[0];
  console.log(`  Project: ${qaReview.project?.name}`);
  console.log(`  QA Issues Count: ${qaReview.developerIssuesCount}`);
  for (const finding of qaReview.findings) {
    console.log(`    • [${finding.severity}] ${finding.title} (${finding.fileName})`);
    if (finding.fileName.includes("Login.jsx") || finding.fileName.includes("productController.js")) {
      throw new Error(`PRIVACY VIOLATION: QA Tester received non-QA finding: ${finding.fileName}`);
    }
  }
  console.log("✓ TEST 4 PASSED: QA Tester received only their own findings.");

  // --- TEST 5: UI/UX DESIGNER REVIEWS ---
  console.log("\n--- TEST 5: UI/UX Designer Manager AI Reviews Retrieval ---");
  const uiuxRes = await fetch(`${baseUrl}/api/code/my-manager-reviews`, {
    headers: { Authorization: `Bearer ${uiuxToken}` },
  });
  console.log("UI/UX Designer status:", uiuxRes.status);
  const uiuxData = await uiuxRes.json();
  const uiuxReview = uiuxData.reviews[0];
  console.log(`  Project: ${uiuxReview.project?.name}`);
  console.log(`  UI/UX Issues Count: ${uiuxReview.developerIssuesCount}`);
  for (const finding of uiuxReview.findings) {
    console.log(`    • [${finding.severity}] ${finding.title} (${finding.fileName})`);
    if (finding.fileName.includes("productController.js") || finding.fileName.includes("ecommerce.test.js")) {
      throw new Error(`PRIVACY VIOLATION: UI/UX received non-UI/UX finding: ${finding.fileName}`);
    }
  }
  console.log("✓ TEST 5 PASSED: UI/UX Designer received only their own findings.");

  // --- TEST 6: SINGLE REVIEW DETAIL ENDPOINT ---
  console.log("\n--- TEST 6: Single Review Detail Endpoint Verification ---");
  const singleRes = await fetch(`${baseUrl}/api/code/my-manager-reviews/${feReview._id}`, {
    headers: { Authorization: `Bearer ${frontendToken}` },
  });
  console.log("Single Review detail status:", singleRes.status);
  const singleData = await singleRes.json();
  if (!singleData.success || !singleData.review) {
    throw new Error(`Single review detail failed: ${JSON.stringify(singleData)}`);
  }
  console.log("  Single Review Project:", singleData.review.project?.name);
  console.log("  Single Review Findings Count:", singleData.review.findings?.length);
  console.log("✓ TEST 6 PASSED: Detailed review modal endpoint functioning correctly.");

  console.log("\n==================================================");
  console.log("ALL 6 MANAGER AI REVIEWS TESTS PASSED! 🎉");
  console.log("==================================================");

  await mongoose.disconnect();
  server.close();
}

runManagerReviewsVerification().catch((err) => {
  console.error("Verification failed with error:", err);
  process.exit(1);
});
